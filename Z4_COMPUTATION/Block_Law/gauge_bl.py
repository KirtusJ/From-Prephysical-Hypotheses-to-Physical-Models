#!/usr/bin/env python3
"""
Block law (BL) for gauge-invariant record rules: exact solution spaces on boxes.

Setting. q >= 2, zeta = exp(2 pi i/q), R = Z[zeta] (coordinates in the power basis
1, zeta, .., zeta^(n-1), n = phi(q)), C = q-th roots of unity.  B is a d x d matrix
with entries in C and B* B = d.  Unknown: Phi : R -> rationals, Phi(0) = 0.
    (BL)  sum_z Phi( sum_y B_zy beta_y ) = d sum_y Phi(beta_y).

Modes.
  gauge   : unknowns are the C-orbits of nonzero elements (Phi(u a) = Phi(a), u in C;
            for odd q the element -a is NOT identified with a).
  nogauge : unknowns are the nonzero elements themselves.
Inputs: beta in S^d, S = {coefficient vectors in [-r, r]^n}, with at most m nonzero
entries (m = 2, .., d).

Boundary.  Outputs leave S; their values are unknowns too, and those near the outer
boundary occur in few equations.  The reported number is the dimension of the
solution space RESTRICTED to the inner region I = (orbits of) nonzero elements of S,
i.e. dim { Phi|_I : Phi solves all equations }.  Convention: zero is excluded from
I and from the unknowns (Phi(0) = 0 is imposed).

Exactness.  A set of rows independent modulo p = 1000003 is selected (hence
independent over Q); on this subsystem the restricted dimension is computed exactly
with FLINT as |I| - (rank(A') - rank(A'_outer columns)).  A subsystem can only have a
larger solution space, so this is an exact UPPER bound.  The exact LOWER bound is the
rank on I of the invariant quadratic forms, which are checked to satisfy every
equation in integer arithmetic.  When the two agree the dimension is exact.

PREDICATES (fixed before the first run; failed ones are kept in the result file).
  H   (hypothesis, per case) entries of B are powers of zeta and B* B = d exactly in R.
      Cases failing H are reported and not used.  The subgroup C_B generated by the
      entries is reported, with whether C_B = C.
  P0  the space of real quadratic forms on V invariant under C has dimension
      phi(q)/2 for q >= 3 and 1 for q = 2 (computed as symmetric S with M^T S M = S).
  P2  every G-invariant quadratic form (G = C in gauge mode, G = C_B in nogauge mode)
      satisfies every generated equation exactly.
  P4  these forms have rank e_G on I, where e_G = dim of G-invariant quadratic forms.
  P3  gauge mode, m = d: restricted dimension (upper bound) == e_C at the LARGEST box
      of the case.  Smaller boxes are run and reported; a smaller box with a larger
      dimension is reported as 'box too small' and is not a failure of P3, but is kept.
  P3s the same at EVERY box size (expected to fail somewhere; kept).
  P5  gauge mode, m = 2 (two-input events only): restricted dimension == e_C.
      Expected to FAIL for the Fourier block d = q = 3 (Re a^3, Im a^3); recorded
      whatever the outcome.
  P6  nogauge mode, m = d: restricted dimension == e_{C_B} at the largest box.
      This is a conjecture as far as non-polynomial Phi are concerned (polynomiality
      is proved only with invariance under the entries of B).
  P7  explicit non-quadratic rules: Re(a^3), Im(a^3) on Z[omega] with Fourier d=q=3 and
      Re(a^4) on Z[i] with Fourier d=q=4:  (a) satisfy all two-input equations of the
      case, (b) violate at least one equation with more inputs.  (a) and (b) are
      recorded separately per rule.
No tolerance is used anywhere: all tests are exact integer tests.
Seed: none (no randomness).  The result file is not overwritten.

Resource limit (added after run 2 was killed during the nogauge case q=8, r=2, about
6500 unknowns; the partial log is kept as run2_killed_partial.log; no predicate was
changed): a run with more than MAXN = 2500 unknowns is recorded as skipped.
"""
import sys, os, json, time, itertools
from math import gcd
import numpy as np
import sympy as sp
import flint

P = 1000003
MAXN = 2500
OFF, BASE = 512, 1024
RESULT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results_gauge_bl.json")


def ring(q):
    x = sp.symbols('x')
    cyc = sp.Poly(sp.cyclotomic_poly(q, x), x)
    n = cyc.degree()
    co = [int(c) for c in cyc.all_coeffs()][::-1]  # low to high, monic
    M1 = np.zeros((n, n), dtype=np.int64)          # multiplication by zeta, column convention
    for i in range(n):
        if i + 1 < n:
            M1[i + 1, i] = 1
        else:
            for j in range(n):
                M1[j, i] = -co[j]
    Mk = [np.eye(n, dtype=np.int64)]
    for k in range(1, q):
        Mk.append(M1 @ Mk[-1])
    assert np.array_equal(M1 @ Mk[-1], Mk[0])
    return n, Mk


def mul(a, b, Mk):
    """product in R of coordinate vectors"""
    n = len(a)
    out = np.zeros(n, dtype=object)
    for i in range(n):
        if a[i]:
            out = out + int(a[i]) * (Mk[i].astype(object) @ np.array(b, dtype=object))
    return out


def check_block(E, q, Mk):
    """H: B* B = d exactly; B_zy = zeta^E[z][y]."""
    d = len(E)
    n = Mk[0].shape[0]
    ok = True
    for y1 in range(d):
        for y2 in range(d):
            s = np.zeros(n, dtype=np.int64)
            for z in range(d):
                s = s + Mk[(E[z][y2] - E[z][y1]) % q][:, 0]
            target = np.zeros(n, dtype=np.int64)
            if y1 == y2:
                target[0] = d
            ok = ok and np.array_equal(s, target)
    g = q
    for row in E:
        for e in row:
            g = gcd(g, e % q)
    return ok, q // g  # order of C_B


def invariant_forms(n, gens):
    """integer basis of symmetric S with M^T S M = S for M in gens"""
    idx = [(i, j) for i in range(n) for j in range(i, n)]
    syms = sp.symbols('s0:%d' % len(idx))
    S = sp.zeros(n, n)
    for (i, j), s in zip(idx, syms):
        S[i, j] = s
        S[j, i] = s
    eqs = []
    for M in gens:
        Ms = sp.Matrix(M.tolist())
        D = Ms.T * S * Ms - S
        eqs += [D[i, j] for i in range(n) for j in range(i, n)]
    A = sp.Matrix([[sp.diff(e, s) for s in syms] for e in eqs]) if eqs else sp.zeros(1, len(idx))
    ns = A.nullspace()
    forms = []
    for v in ns:
        den = sp.ilcm(1, 1, *[sp.fraction(c)[1] for c in v])
        v = v * den
        F = np.zeros((n, n), dtype=np.int64)
        for (i, j), c in zip(idx, v):
            F[i, j] = int(c)
            F[j, i] = int(c)
        forms.append(F)
    return forms


def enc(a):
    k = np.zeros(a.shape[:-1], dtype=np.int64)
    for i in range(a.shape[-1]):
        k = k * BASE + (a[..., i] + OFF)
    return k


def dec(k, n):
    out = np.zeros(n, dtype=np.int64)
    for i in range(n - 1, -1, -1):
        out[i] = k % BASE - OFF
        k //= BASE
    return out


def canon(a, G):
    k = enc(a)
    for M in G[1:]:
        k = np.minimum(k, enc(a @ M.T))
    return k


def select_rows(chunks, N):
    basis = np.zeros((0, N), dtype=np.float64)
    piv = []
    sel = []
    for C in chunks:
        Cm = np.mod(C, P).astype(np.float64)
        if piv:
            Cm = np.mod(Cm - np.mod(Cm[:, piv] @ basis, P), P)
        nz = np.nonzero(Cm.any(axis=1))[0]
        for i in nz:
            v = Cm[i]
            if piv:
                v = np.mod(v - np.mod(v[piv] @ basis, P), P)
            w = np.nonzero(v)[0]
            if len(w) == 0:
                continue
            pc = int(w[0])
            inv = pow(int(v[pc]), P - 2, P)
            v = np.mod(v * inv, P)
            if piv:
                basis = np.mod(basis - np.mod(np.outer(basis[:, pc], v), P), P)
            basis = np.vstack([basis, v])
            piv.append(pc)
            sel.append(C[i].copy())
    return sel


def frank(M):
    if M.shape[0] == 0 or M.shape[1] == 0:
        return 0
    return flint.fmpz_mat(M.shape[0], M.shape[1], [int(x) for x in M.ravel()]).rank()


def run_case(name, q, E, r, m, mode, extra=None):
    t0 = time.time()
    n, Mk = ring(q)
    d = len(E)
    okH, qB = check_block(E, q, Mk)
    res = dict(case=name, q=q, d=d, n=n, r=r, m=m, mode=mode, H=bool(okH), order_C_B=qB,
               C_B_is_C=(qB == q))
    if not okH:
        return res
    gensC = [Mk[1]]
    gensB = [Mk[q // qB]] if qB > 1 else []
    formsC = invariant_forms(n, gensC)
    eC = len(formsC)
    res['e_C'] = eC
    res['P0'] = bool(eC == (1 if q == 2 else n // 2))
    if mode == 'gauge':
        G = Mk
        forms = formsC
    else:
        G = [Mk[0]]
        forms = invariant_forms(n, gensB)
    eG = len(forms)
    res['e_G'] = eG
    # inputs
    S = np.array(list(itertools.product(range(-r, r + 1), repeat=n)), dtype=np.int64)
    s = len(S)
    zero_i = int(np.nonzero(~S.any(axis=1))[0][0])
    idx = np.array(list(itertools.product(range(s), repeat=d)), dtype=np.int32) if s ** d <= 2_000_000 else None
    if idx is None:
        res['skipped'] = 'too many inputs'
        return res
    nnz = (idx != zero_i).sum(axis=1)
    idx = idx[(nnz <= m) & (nnz >= 1)]
    beta = S[idx]                                   # K, d, n
    K = len(beta)
    out = np.zeros((K, d, n), dtype=np.int64)
    for z in range(d):
        for y in range(d):
            out[:, z, :] += beta[:, y, :] @ Mk[E[z][y] % q].T
    kin = np.sort(canon(beta, G), axis=1)
    kout = np.sort(canon(out, G), axis=1)
    sig, first = np.unique(np.hstack([kin, kout]), axis=0, return_index=True)
    nnz_u = (idx[first] != zero_i).sum(axis=1)
    zkey = int(enc(np.zeros(n, dtype=np.int64)))
    keys = np.unique(sig)
    keys = keys[keys != zkey]
    N = len(keys)
    inner_keys = np.unique(canon(S, G))
    inner_keys = inner_keys[inner_keys != zkey]
    inner = np.searchsorted(keys, inner_keys)
    assert np.array_equal(keys[inner], inner_keys)
    outer = np.setdiff1d(np.arange(N), inner)
    U = len(sig)
    res.update(inputs=int(K), equations_unique=int(U), unknowns=int(N), inner=int(len(inner)))

    def rows(lo, hi):
        blk = sig[lo:hi]
        Rm = np.zeros((hi - lo, N + 1), dtype=np.int64)
        col = np.searchsorted(keys, blk)
        col[blk == zkey] = N
        col = np.minimum(col, N)
        rr = np.repeat(np.arange(hi - lo)[:, None], d, axis=1)
        np.add.at(Rm, (rr, col[:, :d]), -d)
        np.add.at(Rm, (rr, col[:, d:]), 1)
        return Rm[:, :N]

    if N > MAXN:
        res['skipped'] = 'more than MAXN unknowns'
        return res
    CH = 1500
    # known solutions
    reps = np.array([dec(int(k), n) for k in keys], dtype=np.int64)
    vals = np.array([np.einsum('ki,ij,kj->k', reps, F, reps) for F in forms], dtype=np.int64).reshape(len(forms), N)
    viol = 0
    for lo in range(0, U, CH):
        Rm = rows(lo, min(U, lo + CH))
        viol += int(np.count_nonzero(Rm @ vals.T)) if len(forms) else 0
    res['P2'] = bool(viol == 0)
    res['P2_violations'] = viol
    lower = frank(vals[:, inner]) if len(forms) else 0
    res['lower_bound'] = int(lower)
    res['P4'] = bool(lower == eG)
    # extra explicit rules
    if extra:
        ex = {}
        for label, fn in extra.items():
            v = np.array([fn(reps[i], Mk) for i in range(N)], dtype=np.int64)
            # gauge invariance of the rule on the unknowns is implied by canonical reps only if fn is invariant: test
            ginv = all(fn(Mk[1] @ reps[i], Mk) == v[i] for i in range(N))
            v2 = 0; vm = 0; n2 = 0; nm = 0
            for lo in range(0, U, CH):
                hi = min(U, lo + CH)
                bad = (rows(lo, hi) @ v) != 0
                two = nnz_u[lo:hi] <= 2
                v2 += int(bad[two].sum()); n2 += int(two.sum())
                vm += int(bad[~two].sum()); nm += int((~two).sum())
            ex[label] = dict(gauge_invariant=bool(ginv), two_input_equations=n2, two_input_violations=v2,
                             more_input_equations=nm, more_input_violations=vm,
                             P7a=bool(v2 == 0), P7b=bool(vm > 0))
        res['extra'] = ex
    # elimination
    sel = select_rows((rows(lo, min(U, lo + CH)) for lo in range(0, U, CH)), N)
    A = np.array(sel, dtype=np.int64).reshape(len(sel), N)
    rk = frank(A)
    rk_out = frank(A[:, outer])
    dimK = rk - rk_out
    upper = len(inner) - dimK
    res.update(rank_mod_p=len(sel), rank_exact_selected=int(rk), rank_outer=int(rk_out),
               nullity_all_unknowns=int(N - rk), restricted_dim_upper=int(upper),
               exact=bool(upper == lower), seconds=round(time.time() - t0, 1))
    return res


def re_power(k, q):
    def fn(a, Mk):
        p = np.zeros(len(a), dtype=object); p[0] = 1
        for _ in range(k):
            p = mul(p, a, Mk)
        if q == 4:
            return int(p[0])
        if q == 3:
            return int(2 * p[0] - p[1])      # 2 Re(c0 + c1 omega)
    return fn


def im_power(k, q):
    def fn(a, Mk):
        p = np.zeros(len(a), dtype=object); p[0] = 1
        for _ in range(k):
            p = mul(p, a, Mk)
        if q == 4:
            return int(p[1])
        if q == 3:
            return int(p[1])                 # Im = c1 sqrt(3)/2
    return fn


def fourier(d, q):
    st = q // d
    return [[(st * z * y) % q for y in range(d)] for z in range(d)]


def had(k, q):
    H = [[0]]
    for _ in range(k):
        H = [r + r for r in H] + [r + [(e + q // 2) % q for e in r] for r in H]
    return H


def two(q):
    return [[0, 1], [0, (1 + q // 2) % q]]


CASES = [
    # name, q, E, radii
    ("Fourier d=q=3", 3, fourier(3, 3), [1, 2, 3]),
    ("Fourier d=q=4", 4, fourier(4, 4), [1, 2]),
    ("Hadamard 2x2 q=2", 2, had(1, 2), [1, 2, 4, 8]),
    ("Hadamard 2x2 q=4", 4, had(1, 4), [1, 2, 3, 4]),
    ("Hadamard 4x4 q=2", 2, had(2, 2), [1, 2, 4]),
    ("Hadamard 4x4 q=4", 4, had(2, 4), [1, 2]),
    ("Fourier d=3 in q=6", 6, fourier(3, 6), [1, 2, 3]),
    ("[[1,z],[1,-z]] q=4", 4, two(4), [1, 2, 3, 4]),
    ("[[1,z],[1,-z]] q=6", 6, two(6), [1, 2, 3, 4]),
    ("[[1,z],[1,-z]] q=8", 8, two(8), [1, 2]),
    ("[[1,z],[1,-z]] q=10 (extra)", 10, two(10), [1, 2]),
    ("[[1,z],[1,-z]] q=12 (extra)", 12, two(12), [1, 2]),
    ("Fourier d=4 in q=8 (extra)", 8, fourier(4, 8), [1]),
    ("Fourier d=q=5 (extra, r=1 only)", 5, fourier(5, 5), []),
    ("NOT a block (H must fail)", 4, [[0, 0], [0, 1]], [1]),
]

EXTRA = {
    "Fourier d=q=3": {"Re a^3": re_power(3, 3), "Im a^3": im_power(3, 3), "Re a^6": re_power(6, 3)},
    "Fourier d=q=4": {"Re a^4": re_power(4, 4), "Im a^4": im_power(4, 4)},
}


def main():
    if os.path.exists(RESULT):
        sys.exit("refusing to overwrite " + RESULT)
    only = sys.argv[1] if len(sys.argv) > 1 else None
    results = []
    for name, q, E, radii in CASES:
        if only and only not in name:
            continue
        d = len(E)
        for r in radii:
            ms = sorted(set([2, d] + ([3] if d > 3 else [])))
            for m in ms:
                res = run_case(name, q, E, r, m, 'gauge', EXTRA.get(name) if m == d else None)
                results.append(res)
                print(json.dumps(res), flush=True)
                if not res['H']:
                    break
            if not results[-1]['H']:
                continue
            res = run_case(name, q, E, r, d, 'nogauge')
            results.append(res)
            print(json.dumps(res), flush=True)
    # predicates per case
    summary = []
    for name, q, E, radii in CASES:
        rs = [x for x in results if x['case'] == name and x.get('H') and 'restricted_dim_upper' in x]
        if not rs:
            summary.append(dict(case=name, H=False if any(x['case'] == name for x in results) else None))
            continue
        d = len(E)
        rmax = max(x['r'] for x in rs)
        g = [x for x in rs if x['mode'] == 'gauge' and x['m'] == d]
        g2 = [x for x in rs if x['mode'] == 'gauge' and x['m'] == 2]
        ng = [x for x in rs if x['mode'] == 'nogauge']
        top = [x for x in g if x['r'] == rmax][0]
        summary.append(dict(
            case=name, H=True, C_B_is_C=top['C_B_is_C'], e_C=top['e_C'],
            P0=all(x['P0'] for x in rs), P2=all(x['P2'] for x in rs), P4=all(x['P4'] for x in rs),
            P3=bool(top['restricted_dim_upper'] == top['e_C']),
            P3s=all(x['restricted_dim_upper'] == x['e_C'] for x in g),
            gauge_dims_by_r={x['r']: x['restricted_dim_upper'] for x in g},
            P5=all(x['restricted_dim_upper'] == x['e_C'] for x in g2 if x['r'] == rmax),
            two_input_dims_by_r={x['r']: x['restricted_dim_upper'] for x in g2},
            P6=all(x['restricted_dim_upper'] == x['e_G'] for x in ng if x['r'] == rmax),
            nogauge_dims_by_r={x['r']: [x['restricted_dim_upper'], x['e_G']] for x in ng},
        ))
    with open(RESULT, 'x') as f:
        json.dump(dict(results=results, summary=summary), f, indent=1)
    print("SUMMARY")
    for s_ in summary:
        print(json.dumps(s_))


if __name__ == '__main__':
    main()
