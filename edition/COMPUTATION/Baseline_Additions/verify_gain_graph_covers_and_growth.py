#!/usr/bin/env python3
"""Checks for the revision of paper G8: (i) the pair measure of the identity indicator is the coincidence count on the derived
covering graph and equals the dimension-weighted mean of the irreducible pair measures; (ii) the growth condition of
Proposition 5.1 in terms of the holonomy group of the gain augmented by length parity.
Writes Gain_Graph_Covers_and_Growth_Results.json."""
import itertools, json
import numpy as np
R = {}; ok = lambda name, val, **info: R.__setitem__(name, dict(passed=bool(val), **info))
rng = np.random.default_rng(2026111234)

def random_graph(n, p):
    while True:
        E = [(i, j) for i in range(n) for j in range(i + 1, n) if rng.random() < p]
        adj = {i: set() for i in range(n)}
        for i, j in E: adj[i].add(j); adj[j].add(i)
        seen = {0}; st = [0]
        while st:
            a = st.pop()
            for b in adj[a]:
                if b not in seen: seen.add(b); st.append(b)
        if len(seen) == n and len(E) >= n: return E
def walks(E, gain, mul, inv, x, k):
    """list of (end vertex, gain) of all walks of length k from x; gain of a walk = product, later edges on the left"""
    nb = {}
    for (i, j) in E:
        nb.setdefault(i, []).append((j, gain[(i, j)])); nb.setdefault(j, []).append((i, inv(gain[(i, j)])))
    out = [(x, None)]
    for _ in range(k): out = [(b, g if cur is None else mul(g, cur)) for a, cur in out for b, g in nb[a]]
    return out

# ---------- (i) cyclic group Z_4 and the symmetric group S_3
# Z_4
n = 6; E = random_graph(n, 0.5); gain = {e: int(rng.integers(4)) for e in E}
W = walks(E, gain, lambda a, b: (a + b) % 4, lambda a: (-a) % 4, 0, 6)
S = [w for w in W if rng.random() < 0.4]
coinc = sum(1 for (y, g) in S for (y2, g2) in S if y == y2 and g == g2)
mu = []
for j in range(4):
    tot = 0.0
    for y in range(n):
        amp = sum(np.exp(2j * np.pi * j * g / 4) for (yy, g) in S if yy == y); tot += abs(amp) ** 2
    mu.append(tot)
ok("C1_Z4_coincidence_count_is_mean_of_character_measures", abs(coinc - sum(mu) / 4) < 1e-6, event_size=len(S), coincidences=coinc, character_measures=[round(m, 6) for m in mu])
# S_3 as permutations of (0,1,2); characters: trivial, sign, standard (fixed points - 1)
perms = list(itertools.permutations(range(3))); pm = lambda a, b: tuple(a[b[i]] for i in range(3)); pinv = lambda a: tuple(sorted(range(3), key=lambda i: a[i]))
sign = lambda a: (-1) ** sum(1 for i in range(3) for j in range(i) if a[j] > a[i]); fix = lambda a: sum(1 for i in range(3) if a[i] == i)
chars = [(1, lambda a: 1), (1, sign), (2, lambda a: fix(a) - 1)]
E = random_graph(n, 0.5); gain = {e: perms[int(rng.integers(6))] for e in E}
W = walks(E, gain, pm, pinv, 0, 5); S = [w for w in W if rng.random() < 0.5]
coinc = sum(1 for (y, g) in S for (y2, g2) in S if y == y2 and g == g2)
mus = [sum(ch(pm(g, pinv(g2))) for (y, g) in S for (y2, g2) in S if y == y2) for d, ch in chars]
ok("C1_S3_coincidence_count_is_dimension_weighted_mean", abs(coinc - sum(d * m for (d, _), m in zip(chars, mus)) / 6) < 1e-9 and all(m >= 0 for m in mus), event_size=len(S), coincidences=coinc, irreducible_measures=[float(m) for m in mus])
# the coincidence count is the pair measure with trivial gains on the derived graph: sum over cover vertices of (number of lifted walks ending there)^2
cnt = {}
for (y, g) in S: cnt[(y, g)] = cnt.get((y, g), 0) + 1
ok("C1_coincidence_count_is_trivial_gain_pair_measure_on_the_cover", coinc == sum(c * c for c in cnt.values()))

# ---------- (ii) growth condition.  Augmented gain (g, parity) in Z_m x Z_2
def holonomy_aug(E, gain, m, n):
    """subgroup of Z_m x Z_2 generated by the augmented gains of closed walks at vertex 0, and one augmented gain to each vertex"""
    nb = {}
    for (i, j) in E:
        nb.setdefault(i, []).append((j, gain[(i, j)])); nb.setdefault(j, []).append((i, (-gain[(i, j)]) % m))
    pot = {0: (0, 0)}; st = [0]; gens = set()
    while st:
        a = st.pop()
        for b, g in nb[a]:
            new = ((pot[a][0] + g) % m, (pot[a][1] + 1) % 2)
            if b not in pot: pot[b] = new; st.append(b)
            else: gens.add(((new[0] - pot[b][0]) % m, (new[1] - pot[b][1]) % 2))
    H = {(0, 0)}
    while True:
        H2 = H | {((a + c) % m, (b + d) % 2) for (a, b) in H for (c, d) in gens}
        if H2 == H: break
        H = H2
    return H, pot
cases = []; allok = True
specs = [("random Z4", 4, None), ("random Z3", 3, None), ("gains in the subgroup {0,2} of Z4", 4, "sub"), ("Z4, every odd closed walk has odd gain", 4, "anti"), ("bipartite graph, Z4", 4, "bip")]
for name, m, kind in specs:
    n = 6
    if kind == "bip":
        E = [(i, j) for i in range(3) for j in range(3, 6) if rng.random() < 0.8]; E = E if len(E) >= 6 else [(i, j) for i in range(3) for j in range(3, 6)]
    else: E = random_graph(n, 0.55)
    gain = {e: int(rng.integers(m)) for e in E}
    if kind == "sub": gain = {e: 2 * int(rng.integers(2)) for e in E}
    if kind == "anti": gain = {e: 1 + 2 * int(rng.integers(2)) for e in E}        # every edge has odd gain: gain parity = length parity
    H, pot = holonomy_aug(E, gain, m, n)
    pred_ok = True; mins = []
    for k in (9, 10, 11, 12):
        W = walks(E, gain, lambda a, b: (a + b) % m, lambda a: (-a) % m, 0, k); cnt = {}
        for y, g in W: cnt[(y, g)] = cnt.get((y, g), 0) + 1
        pred = {(y, g) for y in range(n) for g in range(m) if ((g - pot[y][0]) % m, (k - pot[y][1]) % 2) in H}
        pred_ok &= (set(cnt) == pred); mins.append(min(cnt.values()))
    full = all(len({g for g in range(m) if ((g - pot[y][0]) % m, (k - pot[y][1]) % 2) in H}) in (0, m) for y in range(n) for k in (0, 1))
    cases.append(dict(case=name, order_of_augmented_holonomy_group=len(H), reached_set_equals_coset_prediction=bool(pred_ok), smallest_count_at_lengths_9_to_12=mins, every_gain_reached_at_each_reached_vertex=bool(full)))
    allok &= pred_ok and mins[2] > mins[0] and mins[3] > mins[1]
ok("C2_reached_gains_are_cosets_of_the_augmented_holonomy_group_and_counts_grow", allok, cases=cases, seed=2026111234)
ok("C2_growth_condition_holds_exactly_when_predicted", [c["every_gain_reached_at_each_reached_vertex"] for c in cases][2:4] == [False, False] and cases[4]["every_gain_reached_at_each_reached_vertex"],
   note="cases 3 and 4 fail the condition for the full group; case 5 (bipartite graph) satisfies it when the holonomy group is the whole group; cases 1 and 2 are recorded as drawn")
R["_summary"] = dict(predicates=sum(1 for k in R if not k.startswith("_")), passed=sum(1 for k, v in R.items() if not k.startswith("_") and v["passed"]))
json.dump(R, open("Gain_Graph_Covers_and_Growth_Results.json", "w"), indent=1, default=str)
for k, v in R.items():
    if not k.startswith("_"): print(("PASS " if v["passed"] else "FAIL ") + k)
print(R["_summary"]); print(json.dumps(cases, indent=0))
