#!/usr/bin/env python3
"""build_prod.py -- exact exploration: consistency demanded only on vertex product events.

Carrier: signed arc digraph of the line (N=None) or of a ring with N sites. Vertices (x,d), d=0 (R), 1 (L).
Arcs (x,d)->(x+1,R) gain +1; (x,R)->(x-1,L) gain +1; (x,L)->(x-1,L) gain -1. Start (0,R), gain +1.
A state is the family of pairs (n_plus,n_minus) at the end vertices of an event.
Product events: S = walks with vertex at time s in A_s. Their states are generated by: step, then keep any
subset of vertices. LEMMA used (proved in THEOREM.md, Lemma 1): the law for S is the sum of the laws for the
restrictions of S to one end position, each again a product event; so only one-position states are needed,
and these are computed on backward windows (no enumeration of all events).

Convention: unknown F_key(p,q), p = number of walks of gain +1, q = of gain -1. "Length of an unknown" =
least length at which the pair is realized at that key. Exact rational arithmetic (fractions.Fraction).
No randomness is used (seed 20261113 recorded only for the record).

PREDICATES, fixed before the first run:
 P1 (hypothesis test) every equation generated is satisfied exactly by n=p+q and by (p-q)^2 (per config:
    number of equations tested / passing).
 P2 line, F independent of the vertex (variant V0), all product events of length <= T: the solution space
    projected to unknowns of length <= L has dimension 2 for every 2 <= L <= T-1 ("interior").
 P3 same for F depending on the direction only (V1).
 P4 line, F depending on the vertex (V2): projected dimension equals 2 in the interior.
    (Expected to FAIL: x*(p+q) and golden-ratio amplitude functionals are solutions. Kept as a predicate.)
 P5 ring N in {3,4,5,6}, F depending on the vertex: projected dimension 2 in the interior.
 P6 the rules  F_(x,d)=x*(p+q),  F_(x,R)=(p-q)phi^x, F_(x,L)=(p-q)phi^(x-1)  satisfy every line equation
    exactly (arithmetic in Z[phi]); and F_d=(p-q)w_d, w_R=1,w_L=sqrt2-1 satisfies them with factor sqrt2
    (arithmetic in Z[sqrt2]).
 P7 subfamilies (reads only at the last k times, k=1,2,3; position reads): report the excess over 2; no
    expectation fixed, the attack report says k=1 leaves excess 1.
Usage: build_prod.py RESULT.json Tmax
"""
import sys, json, time
from fractions import Fraction

SEED = 20261113

class Carrier:
    def __init__(self, N, mode, k):
        self.N, self.mode, self.k = N, mode, k
        self.memo = {}
        self.pos = {0: frozenset([0])}
    def nm(self, x):
        return x if self.N is None else x % self.N
    def positions(self, t):
        if t not in self.pos:
            p = self.positions(t - 1)
            self.pos[t] = frozenset(self.nm(x + s) for x in p for s in (1, -1))
        return self.pos[t]
    def B(self, s):
        out = {}
        for (x, d), (p, q) in s:
            xr, xl = self.nm(x + 1), self.nm(x - 1)
            a = out.get((xr, 0), (0, 0)); out[(xr, 0)] = (a[0] + p, a[1] + q)
            if d == 1: p, q = q, p
            a = out.get((xl, 1), (0, 0)); out[(xl, 1)] = (a[0] + p, a[1] + q)
        return out
    def R(self, t, I, k):
        key = (t, I, k)
        if key in self.memo: return self.memo[key]
        if t == 0:
            res = {(((0, 0), (1, 0)),)} if 0 in I else set()
        else:
            Ip = frozenset(self.nm(x + s) for x in I for s in (1, -1)) & self.positions(t - 1)
            prev = self.R(t - 1, Ip, None if k is None else max(k - 1, 0))
            res = set()
            for s in prev:
                b = self.B(s)
                items = sorted((v, m) for v, m in b.items() if v[0] in I)
                if not items: continue
                if k == 0:
                    res.add(tuple(items)); continue
                if self.mode == 'vertex':
                    groups = [[it] for it in items]
                else:
                    g = {}
                    for it in items: g.setdefault(it[0][0], []).append(it)
                    groups = [g[x] for x in sorted(g)]
                for mask in range(1, 1 << len(groups)):
                    sel = []
                    for i, gr in enumerate(groups):
                        if mask >> i & 1: sel.extend(gr)
                    res.add(tuple(sorted(sel)))
        self.memo[key] = res
        return res

def equations(car, T):
    """one-position states of lengths 0..T -> list of (t, x, mR, mL), and realized[(x,d)][m]=first length."""
    eqs = []; first = {}
    for t in range(T + 1):
        for x in sorted(car.positions(t)):
            for s in car.R(t, frozenset([x]), car.k):
                d = dict(s)
                mR = d.get((x, 0), (0, 0)); mL = d.get((x, 1), (0, 0))
                for dd, m in ((0, mR), (1, mL)):
                    if m != (0, 0):
                        first.setdefault((x, dd, m), t)
                eqs.append((t, x, mR, mL))
    return eqs, first

def build(car, T, variant):
    eqs, first = equations(car, T)
    nm = car.nm
    def key(x, d, m):
        if variant == 'V0': return m
        if variant == 'V1': return (d, m)
        return (x, d, m)
    flen = {}
    for (x, d, m), t in first.items():
        k = key(x, d, m); flen[k] = min(flen.get(k, 10**9), t)
    rows = set(); raw = []
    for (t, x, mR, mL) in eqs:
        u = (mR[0] + mL[0], mR[1] + mL[1]); u2 = (mR[0] + mL[1], mR[1] + mL[0])
        terms = [(nm(x + 1), 0, u, 1), (nm(x - 1), 1, u2, 1), (x, 0, mR, -2), (x, 1, mL, -2)]
        row = {}
        for (xx, dd, m, c) in terms:
            if m == (0, 0): continue
            k = key(xx, dd, m)
            row[k] = row.get(k, 0) + c
            if c == 1: flen[k] = min(flen.get(k, 10**9), t + 1)
        raw.append(terms)
        row = {k: c for k, c in row.items() if c != 0}
        if row: rows.add(tuple(sorted(row.items(), key=repr)))
    return eqs, raw, rows, flen

def eliminate(rows, flen):
    """exact echelon form; columns ordered by length descending, so that pivots among columns of length <= L
    count the equations implied on those columns alone."""
    cols = sorted(flen, key=lambda k: (-flen[k], repr(k)))
    idx = {k: i for i, k in enumerate(cols)}
    piv = {}
    for r in sorted(rows, key=repr):
        row = {idx[k]: Fraction(c) for k, c in r}
        while row:
            c = min(row)
            if c in piv:
                f = row[c]; pr = piv[c]
                for j, v in pr.items():
                    nv = row.get(j, 0) - f * v
                    if nv == 0: row.pop(j, None)
                    else: row[j] = nv
            else:
                f = row[c]
                piv[c] = {j: v / f for j, v in row.items()}
                break
    return cols, piv

def qrank(vectors):
    """exact rank of a list of equal-length lists."""
    piv = {}
    for vec in vectors:
        row = {i: Fraction(v) for i, v in enumerate(vec) if v != 0}
        while row:
            c = min(row)
            if c in piv:
                f = row[c]
                for j, v in piv[c].items():
                    nv = row.get(j, 0) - f * v
                    if nv == 0: row.pop(j, None)
                    else: row[j] = nv
            else:
                f = row[c]; piv[c] = {j: v / f for j, v in row.items()}; break
    return len(piv)

def mval(k):
    m = k if not isinstance(k[0], tuple) and len(k) == 2 and not isinstance(k[1], tuple) else k[-1]
    return m

def analyse(N, mode, k, T, variant):
    car = Carrier(N, mode, k)
    t0 = time.time()
    eqs, raw, rows, flen = build(car, T, variant)
    # P1 hypothesis test: model functions satisfy every equation
    ok = 0
    for terms in raw:
        a = sum(c * (m[0] + m[1]) for (_, _, m, c) in terms)
        b = sum(c * (m[0] - m[1]) ** 2 for (_, _, m, c) in terms)
        ok += (a == 0 and b == 0)
    cols, piv = eliminate(rows, flen)
    out = {'carrier': 'line' if N is None else 'ring%d' % N, 'mode': mode, 'reads_last_k': k, 'T': T,
           'variant': variant, 'one_position_states': len(eqs), 'distinct_equations': len(rows),
           'P1_tested': len(raw), 'P1_pass': ok, 'unknowns': len(cols), 'rank': len(piv),
           'nullity': len(cols) - len(piv), 'by_L': []}
    for L in range(1, T + 2):
        cl = [i for i, kk in enumerate(cols) if flen[kk] <= L]
        if not cl: continue
        pl = sum(1 for c in piv if flen[cols[c]] <= L)
        mr = qrank([[mval(cols[i])[0] + mval(cols[i])[1] for i in cl],
                    [(mval(cols[i])[0] - mval(cols[i])[1]) ** 2 for i in cl]])
        out['by_L'].append({'L': L, 'unknowns': len(cl), 'proj_dim': len(cl) - pl, 'model_rank': mr,
                            'excess': len(cl) - pl - mr})
    out['seconds'] = round(time.time() - t0, 1)
    return out, car, raw, flen

class QI:
    """a + b*w with w^2 = r*w + s (phi: r=1,s=1; sqrt2: r=0,s=2)."""
    def __init__(self, a, b, r, s): self.a, self.b, self.r, self.s = a, b, r, s
    def __add__(self, o): return QI(self.a + o.a, self.b + o.b, self.r, self.s)
    def __mul__(self, o):
        if isinstance(o, int): return QI(self.a * o, self.b * o, self.r, self.s)
        return QI(self.a * o.a + self.b * o.b * self.s, self.a * o.b + self.b * o.a + self.b * o.b * self.r,
                  self.r, self.s)
    def zero(self): return self.a == 0 and self.b == 0

def phipow(x):
    one = QI(1, 0, 1, 1); phi = QI(0, 1, 1, 1); inv = QI(-1, 1, 1, 1)
    r = one
    for _ in range(abs(x)): r = r * (phi if x > 0 else inv)
    return r

def counterexamples(raw):
    res = {'tested': len(raw), 'x_times_count': 0, 'golden': 0, 'sqrt2_factor': 0}
    for terms in raw:
        # terms: (x,d,m,c) with c=+1 on the two continuation vertices and -2 on the two end vertices
        a = sum(c * x * (m[0] + m[1]) for (x, d, m, c) in terms)
        res['x_times_count'] += (a == 0)
        g = QI(0, 0, 1, 1)
        for (x, d, m, c) in terms:
            g = g + phipow(x if d == 0 else x - 1) * (c * (m[0] - m[1]))
        res['golden'] += g.zero()
        # factor sqrt2: sum_z F_z = sqrt2 * sum_y F_y ; c=+1 terms are z, c=-2 terms are y (weight 1 each)
        s = QI(0, 0, 0, 2); w = {0: QI(1, 0, 0, 2), 1: QI(-1, 1, 0, 2)}; m2 = QI(0, -1, 0, 2)
        for (x, d, m, c) in terms:
            v = m[0] - m[1]
            s = s + (w[d] * v if c == 1 else w[d] * m2 * v)
        res['sqrt2_factor'] += s.zero()
    return res

def main():
    path = sys.argv[1]; Tmax = int(sys.argv[2])
    f = open(path, 'x')
    results = {'seed': SEED, 'runs': []}
    def run(N, mode, k, T, variant, extra=False):
        out, car, raw, flen = analyse(N, mode, k, T, variant)
        if extra:
            out['P6'] = counterexamples(raw)
            real = {}
            for t in range(T + 1):
                for x in sorted(car.positions(t)):
                    for s in car.R(t, frozenset([x]), car.k):
                        for (v, m) in s: real.setdefault(t, set()).add(m)
            out['realized_pairs_by_length'] = {t: sorted(real[t]) for t in sorted(real)}
        results['runs'].append(out)
        print(json.dumps({k2: v for k2, v in out.items() if k2 != 'realized_pairs_by_length'}), flush=True)
    for T in range(3, Tmax + 1):
        run(None, 'vertex', None, T, 'V0', extra=(T == Tmax))
        run(None, 'vertex', None, T, 'V1')
        run(None, 'vertex', None, T, 'V2')
    for k in (1, 2, 3):
        for T in (Tmax, Tmax + 1):
            run(None, 'vertex', k, T, 'V0'); run(None, 'vertex', k, T, 'V1')
    run(None, 'position', None, Tmax, 'V0'); run(None, 'position', None, Tmax, 'V1')
    for N in (3, 4, 5, 6):
        for T in range(3, Tmax + 1):
            run(N, 'vertex', None, T, 'V2')
    json.dump(results, f, indent=1, default=str); f.close()

if __name__ == '__main__':
    main()
