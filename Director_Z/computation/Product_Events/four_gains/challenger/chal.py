def rank(M):
    M = M.copy() % p; r = 0; rows, cols = M.shape
    for cidx in range(cols):
        if r == rows: break
        nz = np.nonzero(M[r:, cidx])[0]
        if len(nz) == 0: continue
        i = r + nz[0]
        if i != r: M[[r,i]] = M[[i,r]]
        M[r] = M[r] * pow(int(M[r,cidx]), p-2, p) % p
        col = M[:, cidx].copy(); col[r] = 0
        idx = np.nonzero(col)[0]
        if len(idx): M[idx] = (M[idx] - (col[idx,None] * M[r][None,:]) % p) % p
        r += 1
    return r
