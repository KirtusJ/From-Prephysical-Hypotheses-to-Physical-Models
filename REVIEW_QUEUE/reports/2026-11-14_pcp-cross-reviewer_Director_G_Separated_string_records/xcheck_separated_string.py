def pairs_of(n):
    return list(combinations(range(n), 2))


def gate(n, j, c, s, d):
    """Matrix (list of rows) of tilt (c,s)/d on bond (j,j+1)."""
    P = pairs_of(n); N = len(P)
    M = [[Fr(0)] * N for _ in range(N)]
    for k, (x, y) in enumerate(P):
        occ = [j in (x, y), j + 1 in (x, y)]
        if occ[0] == occ[1]:
            M[k][k] = Fr(1); continue
        other = [z for z in (x, y) if z not in (j, j + 1)][0]
        if occ[0]:
            tgt = P.index(tuple(sorted((other, j + 1)))); amp = Fr(s, d)
        else:
            tgt = P.index(tuple(sorted((other, j)))); amp = Fr(-s, d)
        M[k][k] += Fr(c, d); M[tgt][k] += amp
    return M


def mul(A, B):
    n = len(A)
    return [[sum(A[i][k] * B[k][j] for k in range(n)) for j in range(n)] for i in range(n)]


def tr(A):
    return [list(r) for r in zip(*A)]


def red(x, p):
    return x.numerator * pow(x.denominator, -1, p) % p


def labels(A, p):
    """Label of each port's backward effect at prime p, or None if H fails."""
    out = []
    for row in A:  # row j of A = A^T e_j
        r = [red(x, p) for x in row]
        nz = [k for k, v in enumerate(r) if v]
        if len(nz) != 1 or (r[nz[0]] * r[nz[0]]) % p != 1:
            return None
        out.append(nz[0])
    return out


def name(pr):
    return "%d%d" % pr


